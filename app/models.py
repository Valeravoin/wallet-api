# app/models.py

from sqlalchemy import Column, String, Numeric
from sqlalchemy.orm import declarative_base

# Создаём базовый класс для всех моделей.
# Важно: этот Base должен быть ОДИН на весь проект.
# Именно через Base.metadata Alembic видит все таблицы и генерирует миграции.
Base = declarative_base()


class Wallet(Base):
    """
    Модель таблицы wallets для хранения кошельков пользователей.

    Логика выбора типов:
    - UUID как primary_key: позволяет создавать кошельки в разных сервисах
      без риска коллизий (пересечения ID).
    - Numeric(10, 2) для баланса: гарантирует точность до копеек и исключает
      ошибки округления, которые возникают при использовании Float.
    """

    # Явно задаём имя таблицы в базе данных.
    # Во множественном числе — общепринятый стиль именования таблиц.
    __tablename__ = "wallets"

    # Первичный ключ: уникальный идентификатор кошелька в формате UUID.
    # Хранится как строка (String), потому что это универсальный формат,
    # понятный и человеку, и разным микросервисам.
    uuid = Column(String, primary_key=True)

    # Баланс кошелька.
    # precision=10 — всего 10 цифр (до и после запятой).
    # scale=2 — ровно 2 знака после запятой (копейки).
    # default=0.00 — если баланс не передан при создании, он будет 0.
    # Это защищает от NULL-значений и упрощает логику обработки.
    balance = Column(Numeric(precision=10, scale=2), default=0.00)
